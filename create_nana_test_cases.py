def build_cases() -> tuple[list[dict], list[dict]]:
    # Keep the requested first batch at 50 cases while retaining a natural
    # closing-dialogue case at the end of the workbook.
    selected_scenarios = SCENARIOS[:49] + [SCENARIOS[-1]]
    if len(selected_scenarios) != 50:
        raise ValueError(f"Expected 50 selected scenarios, got {len(selected_scenarios)}")

    case_rows: list[dict] = []
    message_rows: list[dict] = []
    base_time = datetime(2026, 8, 12, 8, 23, 49, 135000)
    increments = [3.135, 15.721, 4.424, 17.983, 5.116, 12.807, 4.331, 18.442, 6.208, 14.675]

    for case_id, item in enumerate(selected_scenarios, start=1):
        current = base_time + timedelta(minutes=(case_id - 1) * 11)
        lines: list[str] = []
        for turn_index, (user_text, note) in enumerate(zip(item["prompts"], item["notes"])):
            timestamp = current
            stamp = timestamp.isoformat(timespec="milliseconds")
            lines.append(f"[{stamp}] user: {user_text}")
            message_rows.append({
                "用例编号": f"NANA-{case_id:03d}",
                "场景": item["scene"],
                "消息序号": turn_index * 2 + 1,
                "轮次": turn_index + 1,
                "时间戳": stamp,
                "角色": "user",
                "消息内容": user_text,
            })
            current += timedelta(seconds=increments[turn_index])

            timestamp = current
            stamp = timestamp.isoformat(timespec="milliseconds")
            assistant_text = render_assistant(note, turn_index)
            lines.append(f"[{stamp}] assistant: {assistant_text}")
            message_rows.append({
                "用例编号": f"NANA-{case_id:03d}",
                "场景": item["scene"],
                "消息序号": turn_index * 2 + 2,
                "轮次": turn_index + 1,
                "时间戳": stamp,
                "角色": "assistant",
                "消息内容": assistant_text,
            })
            current += timedelta(seconds=2.7 + (turn_index % 3) * 0.8)

        case_rows.append({
            "用例编号": f"NANA-{case_id:03d}",
            "测试场景": item["scene"],
            "测试目标": item["goal"],
            "消息轮数": 20,
            "交互组数": 10,
            "消息条数": len(lines),
            "对话内容": "\n".join(lines),
        })

    return case_rows, message_rows


